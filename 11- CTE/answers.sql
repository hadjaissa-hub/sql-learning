
## 📝 Практика

Теперь твоя очередь. Сделай **10 задач на CTE**, как мы делали с предыдущими темами.

### Задача 1

Создай CTE `high_salary`, который содержит всех сотрудников с зарплатой больше `5000`. Выведи его.

### Задача 2

Создай CTE `salary_stats`, который считает среднюю зарплату всех сотрудников. Выведи результат.

### Задача 3

Создай CTE `department_stats`, который считает среднюю зарплату каждого отдела.

### Задача 4

Используя CTE `department_stats`, выведи только отделы, где средняя зарплата больше `4000`.

### Задача 5

Создай CTE, который считает количество сотрудников в каждом отделе. Выведи отделы, где сотрудников больше `2`.

### Задача 6

Создай CTE со средней зарплатой каждого отдела и через `JOIN` выведи:

```text
department_name
average_salary
```

### Задача 7

Используя CTE со средней зарплатой отдела, найди сотрудников, которые получают **выше средней зарплаты своего отдела**.

### Задача 8

Создай CTE, который считает:

```text
department_id
total_employees
total_salary
average_salary
```

для каждого отдела.

### Задача 9

Используя CTE из задачи 8, выведи только отделы, где:

```text
total_employees > 2
AND average_salary > 4000
```

### Задача 10 ⭐

Создай CTE со статистикой отделов и через `JOIN` выведи:

```text
department_name
total_employees
average_salary
lowest_salary
highest_salary
```

Отсортируй по `average_salary DESC`.

**Пиши решения всех 10 задач — я проверю каждую и отдельно отмечу синтаксические ошибки, логические ошибки и то, что уже делаешь правильно.**
